create extension if not exists pgcrypto;

create or replace function public.set_updated_at()
returns trigger language plpgsql as $$
begin new.updated_at = now(); return new; end; $$;

create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  display_name text,
  email text,
  role text not null default 'member' check (role in ('member','admin')),
  plan text not null default 'free' check (plan in ('free','pro')),
  subscription_status text not null default 'inactive',
  subscription_id text,
  is_suspended boolean not null default false,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create or replace function public.handle_new_user()
returns trigger language plpgsql security definer set search_path=public as $$
begin
  insert into public.profiles(id,display_name,email)
  values(new.id, coalesce(new.raw_user_meta_data->>'display_name', split_part(new.email,'@',1)), new.email)
  on conflict (id) do nothing;
  return new;
end; $$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created after insert on auth.users for each row execute function public.handle_new_user();

create or replace function public.is_admin()
returns boolean language sql stable security definer set search_path=public as $$
  select exists(select 1 from public.profiles where id=auth.uid() and role='admin' and is_suspended=false);
$$;

create table if not exists public.assets (
  id uuid primary key default gen_random_uuid(),
  title text not null,
  description text default '',
  category text not null default 'Outros',
  subcategory text default '',
  tags text[] not null default '{}',
  media_type text not null default 'archive' check(media_type in ('audio','video','image','archive','project')),
  file_format text,
  file_size bigint,
  cover_url text,
  access_level text not null default 'pro' check(access_level in ('free','pro')),
  status text not null default 'draft' check(status in ('draft','published','paused')),
  download_enabled boolean not null default true,
  preview_enabled boolean not null default true,
  featured boolean not null default false,
  download_count bigint not null default 0,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.asset_files (
  asset_id uuid primary key references public.assets(id) on delete cascade,
  file_key text,
  preview_key text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.tutorials (
  id uuid primary key default gen_random_uuid(),
  title text not null,
  description text default '',
  category text default 'Edição',
  duration_label text default '',
  thumbnail_url text,
  access_level text not null default 'pro' check(access_level in ('free','pro')),
  status text not null default 'draft' check(status in ('draft','published','paused')),
  featured boolean not null default false,
  order_index integer not null default 0,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.tutorial_sources (
  tutorial_id uuid primary key references public.tutorials(id) on delete cascade,
  youtube_id text not null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.favorites (
  user_id uuid not null references public.profiles(id) on delete cascade,
  asset_id uuid not null references public.assets(id) on delete cascade,
  created_at timestamptz not null default now(),
  primary key(user_id,asset_id)
);

create table if not exists public.downloads (
  id bigint generated by default as identity primary key,
  user_id uuid references public.profiles(id) on delete set null,
  asset_id uuid references public.assets(id) on delete set null,
  action text not null default 'download',
  ip_hash text,
  created_at timestamptz not null default now()
);
create index if not exists downloads_user_date_idx on public.downloads(user_id,created_at desc);
create index if not exists downloads_asset_date_idx on public.downloads(asset_id,created_at desc);

create table if not exists public.app_settings (
  key text primary key,
  value jsonb not null,
  updated_at timestamptz not null default now()
);

