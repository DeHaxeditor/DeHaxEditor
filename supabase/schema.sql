create or replace function public.increment_asset_download(asset_uuid uuid)
returns void language sql security definer set search_path=public as $$
  update public.assets set download_count=download_count+1 where id=asset_uuid;
$$;

-- Updated_at triggers
DO $$
BEGIN
  if not exists(select 1 from pg_trigger where tgname='profiles_updated_at') then create trigger profiles_updated_at before update on public.profiles for each row execute function public.set_updated_at(); end if;
  if not exists(select 1 from pg_trigger where tgname='assets_updated_at') then create trigger assets_updated_at before update on public.assets for each row execute function public.set_updated_at(); end if;
  if not exists(select 1 from pg_trigger where tgname='asset_files_updated_at') then create trigger asset_files_updated_at before update on public.asset_files for each row execute function public.set_updated_at(); end if;
  if not exists(select 1 from pg_trigger where tgname='tutorials_updated_at') then create trigger tutorials_updated_at before update on public.tutorials for each row execute function public.set_updated_at(); end if;
  if not exists(select 1 from pg_trigger where tgname='tutorial_sources_updated_at') then create trigger tutorial_sources_updated_at before update on public.tutorial_sources for each row execute function public.set_updated_at(); end if;
END $$;

