create policy profiles_read on public.profiles for select using (id=auth.uid() or public.is_admin());
create policy profiles_admin_update on public.profiles for update using (public.is_admin()) with check (public.is_admin());

create policy assets_catalog on public.assets for select using (status='published' or public.is_admin());
create policy assets_admin_insert on public.assets for insert with check (public.is_admin());
create policy assets_admin_update on public.assets for update using (public.is_admin()) with check (public.is_admin());
create policy assets_admin_delete on public.assets for delete using (public.is_admin());
create policy asset_files_admin on public.asset_files for all using (public.is_admin()) with check (public.is_admin());

create policy tutorials_catalog on public.tutorials for select using (status='published' or public.is_admin());
create policy tutorials_admin_insert on public.tutorials for insert with check (public.is_admin());
create policy tutorials_admin_update on public.tutorials for update using (public.is_admin()) with check (public.is_admin());
create policy tutorials_admin_delete on public.tutorials for delete using (public.is_admin());
create policy tutorial_sources_admin on public.tutorial_sources for all using (public.is_admin()) with check (public.is_admin());

create policy favorites_read on public.favorites for select using (user_id=auth.uid() or public.is_admin());
create policy favorites_insert on public.favorites for insert with check (user_id=auth.uid());
create policy favorites_delete on public.favorites for delete using (user_id=auth.uid() or public.is_admin());

create policy downloads_read on public.downloads for select using (user_id=auth.uid() or public.is_admin());
create policy settings_read on public.app_settings for select using (true);
create policy settings_admin on public.app_settings for all using (public.is_admin()) with check (public.is_admin());

